"""What treating an uncertain relation as exact costs, measured rather than argued.

The kernel's consistency statistic is r^T S^-1 r with S = A P A^T + Sigma_b. That is right
when the RELATION is exact and only b carries error -- true of a conservation law written on
declared states, false of every constitutive relation the roadmap needs next. A Muskingum
routing row carries K and x; a heat-exchanger duty row carries an effectiveness; a
stage-capacity slope is read off a survey. Those coefficients are measured quantities, and the
kernel had no way to say so: b_var declared uncertainty on b and nothing declared it on A.

The second-balance study priced that gap in isolation terms. This prices it in false alarms.

With A = A_bar + E the residual gains E x, so S gains Cov(E x), a QUADRATIC FORM IN THE STATE
rather than a constant. Omitting it does not make the test conservative; it makes the test
reject a system that is behaving exactly as declared. This experiment measures by how much,
over independent draws of a system where the declared model is true by construction:

    the null is TRUE in every draw -- b is generated by the realised relation, the state
    estimate is drawn from its declared covariance, and nothing is faulty. A calibrated
    statistic has mean rank(A) and exceeds its 1-in-100 threshold about 1% of the time.

Three declarations are scored on the same draws:

    A exact              the kernel before this change: Sigma_b only
    A_var, rows independent   a per-row (rows, n, n) declaration
    A_var, full vec(A)        the (rows*n, rows*n) form, which can carry row dependence

The third is the one the roadmap asks for where evidence is shared: "shared flow and
temperature evidence can correlate the rows. An independently declared A_var by itself would
not account for those correlations." The draws here make the rows genuinely dependent, so the
second declaration is wrong in a specific, measurable way rather than merely incomplete.

Truth-free this is not: the generating model IS known here, because the point is to measure a
calibration against a null that is true by construction. No real record appears, and nothing
here says what any instrument does.

    python -m set_lcm.experiments.errors_in_variables  -> results/errors_in_variables.{md,json}
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from ..lcm import chi2_quantile, consistency_stat
from ..schema import ConstraintSet
from .provenance import REPO_ROOT, header_line, provenance

SEED = 20260913
DRAWS = 20000
ALPHA = 0.01

# A two-row relation on three states: one exact conservation row and one constitutive row
# whose middle coefficient is a measured quantity. The shape the roadmap's next stage has.
A_BAR = np.array([[1.0, -1.0, 0.0],
                  [0.0, 0.6, -1.0]])
STATE = np.array([2.0, 5.0, -1.5])
P = np.diag([0.40, 0.25, 0.10])
B_VAR = np.array([0.05, 0.02])

# Declared coefficient uncertainty. Both rows' middle coefficient comes from the same measured
# flow, so their errors move together: that is the shared-evidence case, and SHARED is what a
# per-row declaration cannot say.
ROW0_COEFFICIENT_VAR, ROW1_COEFFICIENT_VAR = 0.02, 0.03
SHARED_COVARIANCE_SWEEP = (0.0, 0.01, 0.02)   # Cov between the two rows' uncertain coefficient

# Cov(E x) is first order in the coefficient error, so a correctly declared A_var should still
# leave a residual miscalibration that SHRINKS as the coefficients get better known. Scaling
# the declared variances down is how that claim gets measured instead of asserted.
COEFFICIENT_SCALE_SWEEP = (1.0, 0.25, 0.0625, 0.01)


def declarations(shared: float) -> dict[str, np.ndarray | None]:
    """The three A declarations compared, and the truth the draws are generated from."""
    n, m = A_BAR.shape[1], A_BAR.shape[0]
    full = np.zeros((m * n, m * n))
    full[1, 1] = ROW0_COEFFICIENT_VAR
    full[n + 1, n + 1] = ROW1_COEFFICIENT_VAR
    full[1, n + 1] = full[n + 1, 1] = shared
    per_row = np.array([np.diag([0.0, ROW0_COEFFICIENT_VAR, 0.0]),
                        np.diag([0.0, ROW1_COEFFICIENT_VAR, 0.0])])
    return {"A treated as exact": None,
            "A_var, rows declared independent": per_row,
            "A_var, full vec(A) covariance": full,
            "__truth__": full}


def draw_statistics(shared: float, draws: int = DRAWS, seed: int = SEED) -> dict:
    """One null experiment: the declared model is true in every draw, by construction."""
    declared = declarations(shared)
    truth = declared.pop("__truth__")
    n, m = A_BAR.shape[1], A_BAR.shape[0]
    rng = np.random.default_rng(seed)
    values = {name: np.empty(draws) for name in declared}
    for k in range(draws):
        E = rng.multivariate_normal(np.zeros(m * n), truth).reshape(m, n)
        A = A_BAR + E                                   # the relation that actually holds
        b = A @ STATE + rng.multivariate_normal(np.zeros(m), np.diag(B_VAR))
        x_hat = STATE + rng.multivariate_normal(np.zeros(n), P)
        for name, A_var in declared.items():
            cs = ConstraintSet("null-draw", A_BAR, b, "the declared relation",
                               b_var=B_VAR, A_var=A_var)
            values[name][k] = consistency_stat(x_hat, P, cs)
    threshold = chi2_quantile(m, 1.0 - ALPHA)
    return {
        "shared_row_covariance": shared, "draws": draws, "seed": seed,
        "rank": m, "alpha": ALPHA, "threshold": float(threshold),
        "by_declaration": {
            name: {
                "mean": float(v.mean()), "median": float(np.median(v)),
                "rejection_rate": float(np.mean(v > threshold)),
                "rejection_rate_over_nominal": float(np.mean(v > threshold) / ALPHA),
                "q99": float(np.quantile(v, 0.99)),
            } for name, v in values.items()},
    }


def approximation_quality(draws: int = DRAWS // 2, seed: int = SEED + 1) -> list[dict]:
    """Does the first-order correction's residual error shrink as the approximation improves?

    Scored on the full declaration only, with independent rows, so the single moving part is
    how well the coefficients are known. If the leftover miscalibration is the dropped second
    order term then it goes away here; if it does not, the correction is wrong in some other
    way and this says so.
    """
    n, m = A_BAR.shape[1], A_BAR.shape[0]
    threshold = chi2_quantile(m, 1.0 - ALPHA)
    out = []
    for scale in COEFFICIENT_SCALE_SWEEP:
        full = np.zeros((m * n, m * n))
        full[1, 1] = ROW0_COEFFICIENT_VAR * scale
        full[n + 1, n + 1] = ROW1_COEFFICIENT_VAR * scale
        rng = np.random.default_rng(seed)
        values = np.empty(draws)
        for k in range(draws):
            E = rng.multivariate_normal(np.zeros(m * n), full).reshape(m, n)
            b = (A_BAR + E) @ STATE + rng.multivariate_normal(np.zeros(m), np.diag(B_VAR))
            x_hat = STATE + rng.multivariate_normal(np.zeros(n), P)
            values[k] = consistency_stat(x_hat, P,
                                         ConstraintSet("scale-draw", A_BAR, b, "the declared relation",
                                                       b_var=B_VAR, A_var=full))
        out.append({"coefficient_scale": scale,
                    "row0_coefficient_variance": ROW0_COEFFICIENT_VAR * scale,
                    "mean": float(values.mean()),
                    "rejection_rate": float(np.mean(values > threshold)),
                    "rejection_rate_over_nominal": float(np.mean(values > threshold) / ALPHA)})
    return out


def compute() -> dict:
    experiments = [draw_statistics(shared) for shared in SHARED_COVARIANCE_SWEEP]
    quality = approximation_quality()
    out = {
        "schema_version": "fsre-errors-in-variables-v1",
        "scope": "A calibration measurement against a null that is true by construction. No "
                 "real record appears; nothing here describes an instrument.",
        "provenance": {"generation": provenance()},
        "declared": {
            "A_bar": A_BAR.tolist(), "state": STATE.tolist(),
            "P_diagonal": np.diag(P).tolist(), "b_var": B_VAR.tolist(),
            "row0_coefficient_variance": ROW0_COEFFICIENT_VAR,
            "row1_coefficient_variance": ROW1_COEFFICIENT_VAR,
            "shared_row_covariance_swept": list(SHARED_COVARIANCE_SWEEP),
            "draws": DRAWS, "seed": SEED, "alpha": ALPHA,
            "null_status": "true by construction in every draw: b is generated by the realised "
                           "relation and the state estimate is drawn from its declared covariance",
        },
        "experiments": experiments,
        "approximation_quality": quality,
        "limitations": [
            "The null is true by construction here, which is what makes this a calibration measurement and not a fault benchmark.",
            "Cov(E x) is first order in the coefficient error: the dropped term is the uncertain coefficients acting on the state error, second order in the two small quantities together. Its residual cost is measured above rather than assumed small.",
            "It is a quadratic form in the state, so a set declaring A_var has a different residual covariance at a different operating point and detectability stops being a property of the set alone.",
            "The projection is unchanged. A declared A_var corrects the consistency TEST; reconciliation still solves against A_bar as though it were exact, so a reported correction remains conditional on that.",
            "Nothing here declares dependence between A's error and b's, or between A's error and the state estimate. Shared evidence produces exactly those, and this experiment does not measure them.",
            "One relation shape, one operating point, one Gaussian coefficient error. A different relation could be more or less sensitive.",
        ],
    }
    out["claims"] = claims(out)
    return out


def claims(r: dict) -> dict:
    """Every qualitative sentence render() prints, as a computed condition."""
    def cell(experiment, name):
        return experiment["by_declaration"][name]
    independent = [e for e in r["experiments"] if e["shared_row_covariance"] == 0.0]
    dependent = [e for e in r["experiments"] if e["shared_row_covariance"] > 0.0]
    return {
        "treating_an_uncertain_relation_as_exact_over_rejects_everywhere": all(
            cell(e, "A treated as exact")["rejection_rate"] > 5 * e["alpha"]
            for e in r["experiments"]),
        "treating_it_as_exact_inflates_the_mean_far_above_the_rank": all(
            cell(e, "A treated as exact")["mean"] > 2.0 * e["rank"] for e in r["experiments"]),
        "the_full_declaration_is_calibrated_everywhere": all(
            abs(cell(e, "A_var, full vec(A) covariance")["mean"] - e["rank"]) < 0.1 * e["rank"]
            and cell(e, "A_var, full vec(A) covariance")["rejection_rate_over_nominal"] < 1.5
            for e in r["experiments"]),
        "a_per_row_declaration_is_enough_only_when_the_rows_are_independent": (
            all(cell(e, "A_var, rows declared independent")["rejection_rate_over_nominal"] < 1.5
                for e in independent)
            and all(cell(e, "A_var, rows declared independent")["rejection_rate_over_nominal"]
                    > cell(e, "A_var, full vec(A) covariance")["rejection_rate_over_nominal"]
                    for e in dependent)),
        "ignoring_row_dependence_costs_less_than_ignoring_A_entirely": all(
            cell(e, "A_var, rows declared independent")["rejection_rate"]
            < cell(e, "A treated as exact")["rejection_rate"] for e in dependent),
        "the_sweep_contains_both_the_independent_and_dependent_cases":
            bool(independent) and bool(dependent),
        "the_residual_miscalibration_shrinks_as_the_coefficients_become_better_known": (
            r["approximation_quality"][-1]["rejection_rate_over_nominal"]
            < r["approximation_quality"][0]["rejection_rate_over_nominal"]),
        "the_best_known_coefficients_reach_the_nominal_rate": abs(
            r["approximation_quality"][-1]["rejection_rate_over_nominal"] - 1.0) < 0.25,
    }


def render(report: dict) -> str:
    failed = [name for name, held in report["claims"].items() if not held]
    if failed:
        raise RuntimeError(f"report text no longer true of the numbers: {failed}; "
                           f"revise render() before writing")
    L: list[str] = []
    A = L.append
    declared = report["declared"]
    A("# What treating an uncertain relation as exact costs")
    A("")
    A(header_line(report["provenance"]["generation"]))
    A("")
    A(report["scope"])
    A("")
    A("The kernel's consistency statistic assumes the relation `A x = b` is exact and only `b` "
      "carries error. That holds for a conservation law written on declared states. It fails "
      "for every constitutive relation the roadmap needs next — a routing row carrying K and "
      "x, a duty row carrying an effectiveness, a stage-capacity slope read off a survey — "
      "because those coefficients are measured quantities. `b_var` declared uncertainty on "
      "`b`; nothing declared it on `A`.")
    A("")
    A(f"Each row below is {declared['draws']:,} draws of a system where **the declared model is "
      f"true**: `b` is generated by the relation that actually holds, the state estimate is "
      f"drawn from its declared covariance, and nothing is faulty. A calibrated statistic has "
      f"mean rank(A) = {report['experiments'][0]['rank']} and exceeds its "
      f"{declared['alpha']:.0%} threshold about {declared['alpha']:.0%} of the time.")
    A("")

    for experiment in report["experiments"]:
        shared = experiment["shared_row_covariance"]
        heading = ("rows independent" if shared == 0.0
                   else f"rows dependent, shared covariance {shared:g}")
        A(f"### {heading}")
        A("")
        A("| declaration | mean statistic | rejection rate at the "
          f"{experiment['alpha']:.0%} threshold | times nominal |")
        A("|---|---:|---:|---:|")
        for name, cell in experiment["by_declaration"].items():
            A(f"| {name} | {cell['mean']:.3f} | {cell['rejection_rate'] * 100:.2f}% | "
              f"**{cell['rejection_rate_over_nominal']:.1f}x** |")
        A("")

    worst = max(e["by_declaration"]["A treated as exact"]["rejection_rate_over_nominal"]
                for e in report["experiments"])
    A(f"**Treating an uncertain relation as exact is not conservative.** It rejects a system "
      f"behaving exactly as declared up to {worst:.0f} times as often as the threshold says, "
      "because the omitted term belongs in the denominator. An operator would be investigating "
      "instruments that are fine.")
    A("")

    dependent = [e for e in report["experiments"] if e["shared_row_covariance"] > 0.0]
    if dependent:
        worst_dependent = max(dependent, key=lambda e: e["shared_row_covariance"])
        per_row = worst_dependent["by_declaration"]["A_var, rows declared independent"]
        full = worst_dependent["by_declaration"]["A_var, full vec(A) covariance"]
        A("**And declaring the rows independent when they are not is a smaller version of the "
          "same error.** The roadmap says an independently declared `A_var` would not account "
          "for correlations from shared evidence. At the widest shared covariance swept, the "
          f"per-row declaration rejects at {per_row['rejection_rate_over_nominal']:.1f}x "
          f"nominal against the full declaration's {full['rejection_rate_over_nominal']:.1f}x. "
          "That is the cost of the shortcut, and it is much smaller than the cost of ignoring "
          "`A` altogether — which is the argument for the shortcut where evidence genuinely is "
          "not shared, not for using it everywhere.")
        A("")

    quality = report["approximation_quality"]
    A("**The correction is first order, and its leftover error behaves like one.** A correctly "
      "declared `A_var` above still rejects at "
      f"{quality[0]['rejection_rate_over_nominal']:.2f}x nominal rather than exactly 1. Scoring "
      "the same declaration while the coefficients get better known says whether that is the "
      "dropped second-order term or something else:")
    A("")
    A("| declared coefficient variance | mean statistic | rejection rate | times nominal |")
    A("|---:|---:|---:|---:|")
    for cell in quality:
        A(f"| {cell['row0_coefficient_variance']:.5f} | {cell['mean']:.3f} | "
          f"{cell['rejection_rate'] * 100:.2f}% | {cell['rejection_rate_over_nominal']:.2f}x |")
    A("")
    A(f"It shrinks from {quality[0]['rejection_rate_over_nominal']:.2f}x to "
      f"{quality[-1]['rejection_rate_over_nominal']:.2f}x as the declared variance falls "
      f"{quality[0]['coefficient_scale'] / quality[-1]['coefficient_scale']:.0f}-fold, which is "
      "what a dropped second-order term does. The correction is not exact and this is the size "
      "of not being exact.")
    A("")

    A("## What this does not fix")
    A("")
    for line in report["limitations"]:
        A(f"- {line}")
    return "\n".join(L) + "\n"


def main(out_dir: Path = REPO_ROOT / "results", *, quiet: bool = False) -> int:
    report = compute()
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    text = render(report)
    (out_dir / "errors_in_variables.md").write_text(text, encoding="utf-8")
    (out_dir / "errors_in_variables.json").write_text(
        json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    if not quiet:
        print(text)
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=REPO_ROOT / "results")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()
    raise SystemExit(main(args.out_dir, quiet=args.quiet))
